/**
 * Deterministic renderers (Sprint 2A.6 / PR4 + GitHub export hardening sprint).
 *
 * Turn a `BuildSquadArtifactPack` (+ optional venture context) into a fixed
 * set of Markdown files that can be committed straight to a GitHub repo, and
 * synthesize the cross-cutting `EvaluationReport` artifact + its Markdown
 * twin (EVALUATION_REPORT.md).
 *
 * Two entry points:
 *   - `renderPack(pack)` — the legacy 5-file scaffold (README/PRD/ARCH/ROADMAP/USER_STORIES).
 *     Kept for back-compat; downstream callers (jobs, UI) now use renderRepoScaffold.
 *   - `renderRepoScaffold(input)` — the full repo-ready file set the hardening
 *     sprint promises: README, VISION, PRD, ARCHITECTURE, ROADMAP, USER_STORIES,
 *     RISKS, EVALUATION_REPORT, DEMO_SCRIPT, docs/personas, docs/research-graph,
 *     docs/validation, docs/build-plan, .gitignore. Always the same shape;
 *     sections lacking inputs render as explicit "_Not produced in this run._"
 *     stubs so the file set is stable.
 *
 * These are pure functions: no I/O, no LLM calls, no randomness. The same
 * inputs always produce the same bytes so a re-export is a no-op commit.
 */
import type {
  BuildSquadArtifactPack,
  BuildSquadUserStory,
  BuyingCommitteeTranscript,
  EvaluationReport,
  EvaluationReportRiskItem,
  PersonaLabPersona,
  ResearchGraph,
  Venture,
  VentureArtifactKind,
  VentureReadinessScore,
  VentureRecommendation,
  VentureRisk,
} from '@foundry/contracts';

export interface ScaffoldFile {
  path: string;
  content: string;
}

// ──────────── renderPack ─────────────────────────────────────────────────

/**
 * Produce the canonical 5-file BuildSquad scaffold:
 *   README.md, PRD.md, ARCHITECTURE.md, ROADMAP.md, USER_STORIES.md
 * Every file is always emitted; sections that the pack lacks render as
 * "_Not produced in this run._" so the README is never half-empty.
 */
export function renderPack(pack: BuildSquadArtifactPack): ScaffoldFile[] {
  return [
    { path: 'README.md', content: renderReadme(pack) },
    { path: 'PRD.md', content: renderPrd(pack) },
    { path: 'ARCHITECTURE.md', content: renderArchitecture(pack) },
    { path: 'ROADMAP.md', content: renderRoadmap(pack) },
    { path: 'USER_STORIES.md', content: renderUserStories(pack) },
  ];
}

function renderReadme(pack: BuildSquadArtifactPack): string {
  const v = pack.productVision;
  const out: string[] = [];
  out.push(`# ${escTitle(v.productPromise) || 'BuildSquad scaffold'}`);
  out.push('');
  out.push(`> Generated by Foundry BuildSquad on ${pack.createdAt} (mode: \`${pack.mode}\`).`);
  out.push('');
  out.push('## Problem');
  out.push(v.problem || '_No problem statement._');
  out.push('');
  out.push('## Target users');
  out.push(...bullets(v.targetUsers));
  out.push('');
  out.push('## Why now');
  out.push(v.whyNow || '_Not specified._');
  out.push('');
  out.push('## Differentiation');
  out.push(...bullets(v.differentiation));
  out.push('');
  out.push('## Success metrics');
  out.push(...bullets(v.successMetrics));
  out.push('');
  out.push('## Repo contents');
  out.push('- [VISION.md](./VISION.md) — Product vision (problem, promise, differentiation)');
  out.push('- [PRD.md](./PRD.md) — Product requirements document');
  out.push('- [ARCHITECTURE.md](./ARCHITECTURE.md) — System architecture brief');
  out.push('- [ROADMAP.md](./ROADMAP.md) — 4-week roadmap + MVP scope');
  out.push('- [USER_STORIES.md](./USER_STORIES.md) — Prioritised user-story backlog');
  out.push('- [RISKS.md](./RISKS.md) — Risk register');
  out.push('- [EVALUATION_REPORT.md](./EVALUATION_REPORT.md) — Readiness + decision rationale');
  out.push('- [DEMO_SCRIPT.md](./DEMO_SCRIPT.md) — Suggested 5-minute walkthrough');
  out.push('- [docs/personas.md](./docs/personas.md) — Synthetic persona cards');
  out.push('- [docs/research-graph.md](./docs/research-graph.md) — Research graph summary');
  out.push('- [docs/validation.md](./docs/validation.md) — Validation decision & evidence');
  out.push('- [docs/build-plan.md](./docs/build-plan.md) — Build-plan index');
  out.push('');
  out.push('> Generated by [Foundry](https://github.com/amit1858/foundry). Re-running export is idempotent.');
  out.push('');
  return out.join('\n');
}

function renderPrd(pack: BuildSquadArtifactPack): string {
  const out: string[] = ['# Product Requirements Document', ''];
  if (!pack.prd) {
    out.push('_PRD not produced in this run._');
    return out.join('\n');
  }
  const prd = pack.prd;
  out.push('## Overview', prd.overview || '_No overview._', '');
  out.push('## Goals', ...bullets(prd.goals), '');
  out.push('## Non-goals', ...bullets(prd.nonGoals), '');
  out.push('## Personas');
  if (prd.personas.length === 0) out.push('_None captured._');
  for (const p of prd.personas) out.push(`- **${p.name}** — ${p.summary}`);
  out.push('');
  out.push('## Requirements');
  if (prd.requirements.length === 0) out.push('_None captured._');
  for (const r of prd.requirements) {
    out.push(`- \`${r.id}\` (${r.type}) — ${r.text}${r.rationale ? ` _— ${r.rationale}_` : ''}`);
  }
  out.push('');
  out.push('## User journeys');
  if (prd.userJourneys.length === 0) out.push('_None captured._');
  for (const j of prd.userJourneys) {
    out.push(`### ${j.title}${j.personaId ? ` _(${j.personaId})_` : ''}`);
    for (let i = 0; i < j.steps.length; i++) out.push(`${i + 1}. ${j.steps[i]}`);
    out.push('');
  }
  out.push('## Metrics', ...bullets(prd.metrics), '');
  out.push('## Risks', ...bullets(prd.risks), '');
  return out.join('\n');
}

function renderArchitecture(pack: BuildSquadArtifactPack): string {
  const out: string[] = ['# Architecture brief', ''];
  if (!pack.architectureBrief) {
    out.push('_Architecture brief not produced in this run._');
    return out.join('\n');
  }
  const a = pack.architectureBrief;
  out.push('## Components');
  if (a.components.length === 0) out.push('_None captured._');
  for (const c of a.components) out.push(`- **${c.name}** — ${c.responsibility}`);
  out.push('');
  out.push('## Data flow', ...bullets(a.dataFlow), '');
  out.push('## Integrations', ...bullets(a.integrations), '');
  out.push('## Storage', ...bullets(a.storage), '');
  out.push('## Security', ...bullets(a.security), '');
  out.push('## Scalability assumptions', ...bullets(a.scalabilityAssumptions), '');
  return out.join('\n');
}

function renderRoadmap(pack: BuildSquadArtifactPack): string {
  const out: string[] = ['# 4-week roadmap', ''];
  if (!pack.roadmap) {
    out.push('_Roadmap not produced in this run._');
    return out.join('\n');
  }
  for (const w of pack.roadmap.weeks) {
    out.push(`## Week ${w.week} — ${w.theme}`);
    out.push(...bullets(w.deliverables));
    out.push('');
  }
  out.push('## Future backlog', ...bullets(pack.roadmap.futureBacklog), '');
  if (pack.mvpScope) {
    out.push('## MVP scope');
    out.push('### Must-have', ...bullets(pack.mvpScope.mustHave), '');
    out.push('### Should-have', ...bullets(pack.mvpScope.shouldHave), '');
    out.push('### Later', ...bullets(pack.mvpScope.later), '');
    if (pack.mvpScope.explicitCuts.length > 0) {
      out.push('### Explicit cuts');
      for (const c of pack.mvpScope.explicitCuts) out.push(`- **${c.item}** — ${c.reason}`);
      out.push('');
    }
  }
  return out.join('\n');
}

function renderUserStories(pack: BuildSquadArtifactPack): string {
  const out: string[] = ['# User stories', ''];
  if (!pack.userStories || pack.userStories.length === 0) {
    out.push('_No user stories produced in this run._');
    return out.join('\n');
  }
  const grouped: Record<BuildSquadUserStory['priority'], BuildSquadUserStory[]> = {
    must: [], should: [], later: [],
  };
  for (const s of pack.userStories) grouped[s.priority].push(s);
  for (const [priority, label] of [['must', 'Must-have'], ['should', 'Should-have'], ['later', 'Later']] as const) {
    const list = grouped[priority];
    if (list.length === 0) continue;
    out.push(`## ${label}`, '');
    for (const s of list) {
      out.push(`### \`${s.id}\` — ${s.title}${s.personaId ? ` _(${s.personaId})_` : ''}`);
      out.push(`> ${s.story}`, '');
      out.push('**Acceptance criteria**');
      out.push(...bullets(s.acceptanceCriteria));
      out.push('');
    }
  }
  return out.join('\n');
}

// ──────────── renderRepoScaffold ─────────────────────────────────────────
//
// Full repo-ready file set. Always emits the same paths so a re-export is a
// no-op commit. Sections without inputs render explicit "_Not produced in
// this run._" stubs.

export interface RenderRepoScaffoldInput {
  venture: Venture;
  pack: BuildSquadArtifactPack;
  recommendation: VentureRecommendation | null;
  personas: PersonaLabPersona[] | null;
  graph: ResearchGraph | null;
  committee: BuyingCommitteeTranscript | null;
  /** Pre-rendered EVALUATION_REPORT.md text. */
  evaluationMarkdown: string;
  /** Optional venture summary readiness, for the build-plan index. */
  readiness?: VentureReadinessScore;
}

/**
 * Produce the full 14-file repo scaffold the GitHub export hardening sprint
 * promises. Order is deterministic.
 */
export function renderRepoScaffold(input: RenderRepoScaffoldInput): ScaffoldFile[] {
  const { pack } = input;
  const baseFiles = renderPack(pack); // README + PRD + ARCHITECTURE + ROADMAP + USER_STORIES
  return [
    ...baseFiles,
    { path: 'VISION.md', content: renderVision(pack) },
    { path: 'RISKS.md', content: renderRisks(input) },
    { path: 'EVALUATION_REPORT.md', content: input.evaluationMarkdown },
    { path: 'DEMO_SCRIPT.md', content: renderDemoScript(input) },
    { path: 'docs/personas.md', content: renderPersonasDoc(input.personas) },
    { path: 'docs/research-graph.md', content: renderResearchGraphDoc(input.graph) },
    { path: 'docs/validation.md', content: renderValidationDoc(input.recommendation, input.committee) },
    { path: 'docs/build-plan.md', content: renderBuildPlanDoc(pack, input.readiness) },
    { path: '.gitignore', content: renderGitignore() },
  ];
}

