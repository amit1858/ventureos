function renderRisks(input: RenderRepoScaffoldInput): string {
  const out: string[] = ['# Risk register', ''];
  const rec = input.recommendation;
  const recRisks = rec?.risks ?? [];
  const contradictions = input.graph?.contradictions ?? [];
  const critiques = input.pack.agentCritiques ?? [];

  if (recRisks.length === 0 && contradictions.length === 0 && critiques.length === 0) {
    out.push('_No risks captured. Run VentureLab and BuildSquad to surface assumptions and counter-signals._');
    return out.join('\n');
  }

  if (recRisks.length > 0) {
    out.push('## Validation risks');
    out.push('| Risk | Impact | Likelihood | Mitigation |');
    out.push('| --- | --- | --- | --- |');
    for (const r of recRisks) {
      out.push(`| ${escapeCell(r.risk)} | ${r.impact} | ${r.likelihood} | ${escapeCell(r.mitigation || '_TBD_')} |`);
    }
    out.push('');
  }

  if (contradictions.length > 0) {
    out.push('## Research contradictions');
    for (const c of contradictions) out.push(`- ${c}`);
    out.push('');
  }

  const blockers = critiques.filter((c) => c.severity === 'blocker');
  const warnings = critiques.filter((c) => c.severity === 'warning');
  if (blockers.length + warnings.length > 0) {
    out.push('## Build-plan critiques');
    for (const c of [...blockers, ...warnings]) {
      out.push(`- **[${c.severity}] ${c.role} → ${c.targetSection}** — ${c.comment}${c.suggestion ? ` _Suggestion:_ ${c.suggestion}` : ''}`);
    }
    out.push('');
  }
  return out.join('\n');
}

function renderDemoScript(input: RenderRepoScaffoldInput): string {
  const v = input.pack.productVision;
  const rec = input.recommendation;
  const personas = input.personas ?? [];
  const stories = input.pack.userStories ?? [];
  const must = stories.filter((s) => s.priority === 'must').slice(0, 3);

  const out: string[] = [`# Demo script — ${input.venture.title}`, ''];
  out.push('> A suggested 5-minute walkthrough of this venture.');
  out.push('> Generated by Foundry; edit freely once you have a real recording.');
  out.push('');
  out.push('## 0:00 — Problem');
  out.push(v.problem || '_Problem statement not captured._');
  out.push('');
  out.push('## 0:45 — Who feels it');
  if (personas.length === 0) {
    out.push('_No personas attached._');
  } else {
    for (const p of personas.slice(0, 3)) out.push(`- **${p.name}** (${p.role}) — "${p.quote || p.goals[0] || ''}"`);
  }
  out.push('');
  out.push('## 1:30 — Our promise');
  out.push(v.productPromise || '_Not specified._');
  out.push('');
  out.push('## 2:15 — Why now');
  out.push(v.whyNow || '_Not specified._');
  out.push('');
  out.push('## 3:00 — Live walkthrough (3 must-have stories)');
  if (must.length === 0) {
    out.push('_No must-have user stories captured — generate a BuildSquad pack to populate this._');
  } else {
    for (const s of must) out.push(`- \`${s.id}\` ${s.title}`);
  }
  out.push('');
  out.push('## 4:00 — The decision');
  if (rec) {
    out.push(`- **VentureLab recommendation:** ${rec.decision} (score ${rec.overallScore}/100, confidence ${(rec.confidenceScore * 100).toFixed(0)}%).`);
    if (rec.decisionRationale.length > 0) {
      out.push('- Top rationale:');
      for (const r of rec.decisionRationale.slice(0, 3)) out.push(`  - ${r}`);
    }
  } else {
    out.push('_No VentureLab recommendation yet — run VentureLab and re-export to populate._');
  }
  out.push('');
  out.push('## 4:30 — What we built next');
  out.push(`- See [PRD.md](./PRD.md), [ROADMAP.md](./ROADMAP.md), [USER_STORIES.md](./USER_STORIES.md).`);
  out.push(`- See [EVALUATION_REPORT.md](./EVALUATION_REPORT.md) for the readiness scorecard.`);
  out.push('');
  return out.join('\n');
}

function renderPersonasDoc(personas: PersonaLabPersona[] | null): string {
  const out: string[] = ['# Personas', ''];
  if (!personas || personas.length === 0) {
    out.push('_No persona set attached. Generate one in PersonaLab and re-export._');
    return out.join('\n');
  }
  out.push(`> ${personas.length} synthetic persona${personas.length === 1 ? '' : 's'} from PersonaLab.`);
  out.push('');
  for (const p of personas) {
    out.push(`## ${p.name} — ${p.role}`);
    if (p.businessContext) out.push(`> _${p.businessContext}_`);
    if (p.quote) out.push('', `“${p.quote}”`);
    out.push('');
    out.push(`- **Decision power:** ${p.decisionPower}`);
    out.push(`- **Confidence:** ${(p.confidenceScore * 100).toFixed(0)}%`);
    if (p.goals.length > 0) {
      out.push('- **Goals:**');
      for (const g of p.goals) out.push(`  - ${g}`);
    }
    if (p.painPoints.length > 0) {
      out.push('- **Pain points:**');
      for (const x of p.painPoints) out.push(`  - ${x}`);
    }
    if (p.motivations.length > 0) {
      out.push('- **Motivations:**');
      for (const m of p.motivations) out.push(`  - ${m}`);
    }
    if (p.objections.length > 0) {
      out.push('- **Objections:**');
      for (const o of p.objections) out.push(`  - ${o}`);
    }
    if (p.buyingTriggers.length > 0) {
      out.push('- **Buying triggers:**');
      for (const t of p.buyingTriggers) out.push(`  - ${t}`);
    }
    out.push('');
  }
  return out.join('\n');
}

function renderResearchGraphDoc(graph: ResearchGraph | null): string {
  const out: string[] = ['# Research graph', ''];
  if (!graph) {
    out.push('_No research graph attached. Run Graphify and re-export._');
    return out.join('\n');
  }
  const nodes = graph.stats?.nodes ?? graph.nodes?.length ?? 0;
  const edges = graph.stats?.edges ?? graph.edges?.length ?? 0;
  const communities = graph.stats?.communities ?? 0;
  out.push(`> ${nodes} nodes · ${edges} edges · ${communities} communities.`);
  out.push('');

  if (graph.godNodes && graph.godNodes.length > 0) {
    out.push('## Top god-nodes');
    out.push('| Label | Degree | Community |');
    out.push('| --- | --- | --- |');
    for (const g of graph.godNodes.slice(0, 10)) {
      out.push(`| ${escapeCell(g.label)} | ${g.degree} | ${g.community} |`);
    }
    out.push('');
  }

  if (graph.contradictions && graph.contradictions.length > 0) {
    out.push('## Contradictions');
    for (const c of graph.contradictions) out.push(`- ${c}`);
    out.push('');
  }

  if (graph.surprisingConnections && graph.surprisingConnections.length > 0) {
    out.push('## Surprising connections');
    for (const c of graph.surprisingConnections) out.push(`- ${c}`);
    out.push('');
  }

  if (graph.sources && graph.sources.length > 0) {
    out.push('## Sources');
    for (const s of graph.sources.slice(0, 20)) {
      const label = (s as { title?: string; url?: string; id?: string }).title
        ?? (s as { title?: string; url?: string; id?: string }).url
        ?? (s as { title?: string; url?: string; id?: string }).id
        ?? 'source';
      out.push(`- ${label}`);
    }
    out.push('');
  }
  return out.join('\n');
}

function renderValidationDoc(
  rec: VentureRecommendation | null,
  committee: BuyingCommitteeTranscript | null,
): string {
  const out: string[] = ['# Validation', ''];
  if (!rec) {
    out.push('_No VentureLab recommendation yet. Run VentureLab and re-export._');
    return out.join('\n');
  }
  out.push(`## Decision: ${rec.decision}`);
  out.push(`- **Overall score:** ${rec.overallScore}/100`);
  out.push(`- **Confidence:** ${(rec.confidenceScore * 100).toFixed(0)}%`);
  out.push('');
  out.push('## Executive summary');
  out.push(rec.executiveSummary || '_Not specified._');
  out.push('');
  if (rec.decisionRationale.length > 0) {
    out.push('## Decision rationale');
    for (const r of rec.decisionRationale) out.push(`- ${r}`);
    out.push('');
  }
  if (rec.scores.length > 0) {
    out.push('## Scorecard');
    out.push('| Dimension | Score | Direction | Explanation |');
    out.push('| --- | --- | --- | --- |');
    for (const s of rec.scores) {
      out.push(`| ${s.dimension} | ${s.score} | ${s.higherIsBetter ? 'higher = better' : 'lower = better'} | ${escapeCell(s.explanation)} |`);
    }
    out.push('');
  }
  if (rec.evidence.length > 0) {
    out.push('## Evidence');
    for (const e of rec.evidence.slice(0, 10)) {
      out.push(`- _${e.source}_ (weight ${e.weight}) — "${e.quote}"`);
    }
    out.push('');
  }
  if (rec.counterSignals.length > 0) {
    out.push('## Counter-signals');
    for (const e of rec.counterSignals.slice(0, 10)) {
      out.push(`- _${e.source}_ (weight ${e.weight}) — "${e.quote}"`);
    }
    out.push('');
  }
  if (rec.assumptions.length > 0) {
    out.push('## Assumptions');
    for (const a of rec.assumptions) {
      out.push(`- \`${a.id}\` (${a.type}, ${a.confidence}) — ${a.text}${a.validationStrategy ? ` _Validation:_ ${a.validationStrategy}` : ''}`);
    }
    out.push('');
  }
  if (rec.nextSteps.length > 0) {
    out.push('## Next steps');
    for (const s of rec.nextSteps) {
      out.push(`- _(${s.category}, p${s.priority}, effort ${s.effort})_ ${s.title}${s.blocksDecision ? ' **— blocks decision**' : ''}`);
    }
    out.push('');
  }
  if (committee) {
    out.push('## Buying committee');
    out.push(`- **Decision:** ${committee.decision}`);
    if (committee.decisionRationale) out.push(`- **Rationale:** ${committee.decisionRationale}`);
    if (committee.nextSteps.length > 0) {
      out.push('- **Next steps:**');
      for (const s of committee.nextSteps) out.push(`  - ${s}`);
    }
    out.push('');
  }
  return out.join('\n');
}

function renderBuildPlanDoc(
  pack: BuildSquadArtifactPack,
  readiness: VentureReadinessScore | undefined,
): string {
  const out: string[] = ['# Build plan', ''];
  out.push(`> BuildSquad mode: \`${pack.mode}\` · generated ${pack.createdAt}.`);
  out.push('');
  if (readiness) {
    out.push('## Readiness snapshot');
    out.push(`- **Overall:** ${readiness.overall}/100`);
    out.push(`- Persona coverage: ${readiness.personaCoverage}`);
    out.push(`- Research coverage: ${readiness.researchCoverage}`);
    out.push(`- Validation confidence: ${readiness.validationConfidence}`);
    out.push(`- BuildSquad completeness: ${readiness.buildsquadCompleteness}`);
    out.push(`- Risk coverage: ${readiness.riskCoverage}`);
    out.push('');
  }
  out.push('## Sections');
  out.push('- [PRD.md](./PRD.md) — Goals, requirements, journeys, metrics, risks.');
  out.push('- [ARCHITECTURE.md](./ARCHITECTURE.md) — Components, data flow, integrations, security.');
  out.push('- [ROADMAP.md](./ROADMAP.md) — 4-week roadmap + MVP scope.');
  out.push('- [USER_STORIES.md](./USER_STORIES.md) — Must/should/later stories with acceptance criteria.');
  out.push('- [RISKS.md](./RISKS.md) — Risk register.');
  if (pack.prototypeBrief) {
    out.push('');
    out.push('## Prototype brief');
    if (pack.prototypeBrief.pages.length > 0) {
      out.push('### Pages');
      for (const p of pack.prototypeBrief.pages) out.push(`- **${p.name}** — ${p.purpose}`);
    }
    if (pack.prototypeBrief.flows.length > 0) {
      out.push('### Flows');
      for (const f of pack.prototypeBrief.flows) {
        out.push(`- **${f.name}**`);
        for (const s of f.steps) out.push(`  - ${s}`);
      }
    }
    if (pack.prototypeBrief.uiComponents.length > 0) {
      out.push('### UI components');
      out.push(...bullets(pack.prototypeBrief.uiComponents));
    }
    if (pack.prototypeBrief.demoScenario) {
      out.push('### Demo scenario');
      out.push(pack.prototypeBrief.demoScenario);
    }
    out.push('');
  }
  if (pack.agentCritiques.length > 0) {
    out.push('## Agent critiques');
    for (const c of pack.agentCritiques) {
      out.push(`- _[${c.severity}] ${c.role} → ${c.targetSection}_ — ${c.comment}${c.suggestion ? ` _Suggestion:_ ${c.suggestion}` : ''}`);
    }
    out.push('');
  }
  if (pack.rationale.length > 0) {
    out.push('## Orchestrator notes');
    for (const r of pack.rationale) out.push(`- ${r}`);
    out.push('');
  }
  return out.join('\n');
}

