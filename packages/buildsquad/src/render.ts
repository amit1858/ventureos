// ──────────── renderEvaluationReport ─────────────────────────────────────

export interface RenderEvaluationReportInput {
  venture: Venture;
  pack: BuildSquadArtifactPack | null;
  recommendation: VentureRecommendation | null;
  personas: PersonaLabPersona[] | null;
  graph: ResearchGraph | null;
  committee: BuyingCommitteeTranscript | null;
  readiness: VentureReadinessScore;
  /** Stable, monotonic generator id for change tracking. */
  generatorVersion?: string;
  /** Provenance: which source artifact versions fed the report. */
  sourceArtifacts?: { kind: VentureArtifactKind; version: number }[];
  /** Override clock (tests). */
  now?: () => Date;
}

export interface RenderEvaluationReportOutput {
  artifact: EvaluationReport;
  /** Single-file Markdown render destined for EVALUATION_REPORT.md. */
  markdown: string;
}

export function renderEvaluationReport(input: RenderEvaluationReportInput): RenderEvaluationReportOutput {
  const generatedAt = (input.now ?? (() => new Date()))().toISOString();
  const generatorVersion = input.generatorVersion ?? 'evaluation-report@1';

  const personaCount = input.personas?.length ?? 0;
  const personaCoverage = {
    score: clamp01(personaCount === 0 ? 0 : Math.min(1, personaCount / 5)),
    count: personaCount,
    notes: personaNotes(input.personas),
  };

  const nodeCount = input.graph?.stats?.nodes ?? 0;
  const godNodeCount = input.graph?.godNodes?.length ?? 0;
  const contradictionCount = input.graph?.contradictions?.length ?? 0;
  const researchCoverage = {
    score: clamp01(nodeCount === 0 ? 0 : Math.min(1, nodeCount / 40)),
    nodeCount,
    godNodeCount,
    contradictionCount,
    topGodNodes: (input.graph?.godNodes ?? []).slice(0, 5).map((n) => ({
      label: n.label,
      weight: n.degree,
    })),
    notes: researchNotes(input.graph),
  };

  const risks = collectRisks(input.recommendation, input.committee, input.graph);
  const contradictionsPairs: { left: string; right: string }[] = (input.graph?.contradictions ?? []).map((c) => {
    const [left, right] = c.split('↔').map((s) => s.trim());
    return { left: left ?? c, right: right ?? '' };
  });
  const riskCoverage = {
    score: clamp01(risks.length === 0 ? 0 : Math.min(1, risks.length / 5)),
    identifiedRisks: risks,
    contradictions: contradictionsPairs,
    notes: riskNotes(risks, contradictionsPairs),
  };

  const rec = input.recommendation;
  const assumptions = (rec?.assumptions ?? []).map((a) => a.text);
  const openQuestions = (rec?.nextSteps ?? [])
    .filter((s) => s.blocksDecision)
    .map((s) => s.title);
  const validationRoadmap = {
    nextSteps: (rec?.nextSteps ?? []).slice(0, 8).map((s) => ({
      label: s.title,
      ...(s.category ? { owner: s.category } : {}),
    })),
    successCriteria: deriveSuccessCriteria(input.pack),
    killCriteria: deriveKillCriteria(rec),
  };

  const artifact: EvaluationReport = {
    kind: 'EvaluationReport',
    reportId: `er_${input.venture.ventureId}_${generatedAt.replace(/[^0-9]/g, '').slice(0, 14)}`,
    ventureId: input.venture.ventureId,
    generatedAt,
    generatorVersion,
    venture: {
      id: input.venture.ventureId,
      title: input.venture.title,
      status: input.venture.status,
      ...(input.venture.region ? { region: input.venture.region } : {}),
      ...(input.venture.customerType ? { customerType: input.venture.customerType } : {}),
    },
    readinessScore: input.readiness,
    recommendation: {
      decision: rec?.decision ?? null,
      confidence: rec?.confidenceScore ?? null,
      rationale: rec?.decisionRationale ?? [],
      ...(rec?.decision === 'PIVOT' && input.pack?.pivot
        ? { pivotOptions: [input.pack.pivot.revisedMvpDirection] }
        : {}),
    },
    coverage: {
      persona: personaCoverage,
      research: researchCoverage,
      risk: riskCoverage,
    },
    assumptions,
    openQuestions,
    validationRoadmap,
    provenance: {
      sourceArtifacts: input.sourceArtifacts ?? [],
    },
  };

  return { artifact, markdown: renderEvaluationMarkdown(artifact) };
}

function renderEvaluationMarkdown(r: EvaluationReport): string {
  const out: string[] = [];
  out.push(`# Evaluation report — ${r.venture.title}`);
  out.push('');
  out.push(`> Generated ${r.generatedAt} · \`${r.generatorVersion}\``);
  out.push('');
  out.push('## Readiness score');
  out.push(`- **Overall:** ${r.readinessScore.overall} / 100`);
  out.push(`- Persona coverage: ${r.readinessScore.personaCoverage}`);
  out.push(`- Research coverage: ${r.readinessScore.researchCoverage}`);
  out.push(`- Validation confidence: ${r.readinessScore.validationConfidence}`);
  out.push(`- BuildSquad completeness: ${r.readinessScore.buildsquadCompleteness}`);
  out.push(`- Risk coverage: ${r.readinessScore.riskCoverage}`);
  if (r.readinessScore.warnings.length > 0) {
    out.push('', '**Warnings**');
    out.push(...bullets(r.readinessScore.warnings));
  }
  out.push('');
  out.push('## Recommendation');
  out.push(`- **Decision:** ${r.recommendation.decision ?? '_none yet_'}`);
  if (r.recommendation.confidence != null) {
    out.push(`- Confidence: ${(r.recommendation.confidence * 100).toFixed(0)}%`);
  }
  if (r.recommendation.rationale.length > 0) {
    out.push('', '### Rationale');
    out.push(...bullets(r.recommendation.rationale));
  }
  if (r.recommendation.pivotOptions && r.recommendation.pivotOptions.length > 0) {
    out.push('', '### Pivot direction');
    out.push(...bullets(r.recommendation.pivotOptions));
  }
  out.push('');
  out.push('## Coverage');
  out.push(`- Persona: ${(r.coverage.persona.score * 100).toFixed(0)}% (${r.coverage.persona.count} personas)`);
  out.push(...indentBullets(r.coverage.persona.notes));
  out.push(`- Research: ${(r.coverage.research.score * 100).toFixed(0)}% (${r.coverage.research.nodeCount} nodes, ${r.coverage.research.godNodeCount} god-nodes, ${r.coverage.research.contradictionCount} contradictions)`);
  if (r.coverage.research.topGodNodes.length > 0) {
    out.push('  - Top god-nodes:');
    for (const g of r.coverage.research.topGodNodes) out.push(`    - ${g.label} (weight ${g.weight})`);
  }
  out.push(...indentBullets(r.coverage.research.notes));
  out.push(`- Risk: ${(r.coverage.risk.score * 100).toFixed(0)}% (${r.coverage.risk.identifiedRisks.length} risks)`);
  for (const risk of r.coverage.risk.identifiedRisks) {
    out.push(`  - _${risk.severity}_ (${risk.source}) — ${risk.label}`);
  }
  if (r.coverage.risk.contradictions.length > 0) {
    out.push('  - Contradictions:');
    for (const c of r.coverage.risk.contradictions) out.push(`    - ${c.left}${c.right ? ` ↔ ${c.right}` : ''}`);
  }
  out.push('');
  if (r.assumptions.length > 0) {
    out.push('## Assumptions');
    out.push(...bullets(r.assumptions));
    out.push('');
  }
  if (r.openQuestions.length > 0) {
    out.push('## Open questions');
    out.push(...bullets(r.openQuestions));
    out.push('');
  }
  out.push('## Validation roadmap');
  out.push('### Next steps');
  if (r.validationRoadmap.nextSteps.length === 0) out.push('_None._');
  for (const s of r.validationRoadmap.nextSteps) {
    out.push(`- ${s.label}${s.owner ? ` _(${s.owner})_` : ''}`);
  }
  out.push('', '### Success criteria');
  out.push(...bullets(r.validationRoadmap.successCriteria));
  out.push('', '### Kill criteria');
  out.push(...bullets(r.validationRoadmap.killCriteria));
  out.push('');
  if (r.provenance.sourceArtifacts.length > 0) {
    out.push('## Provenance');
    for (const s of r.provenance.sourceArtifacts) out.push(`- ${s.kind} v${s.version}`);
    out.push('');
  }
  return out.join('\n');
}

// ──────────── helpers ────────────────────────────────────────────────────

function bullets(items: string[] | undefined): string[] {
  if (!items || items.length === 0) return ['_None._'];
  return items.map((i) => `- ${i}`);
}

function indentBullets(items: string[]): string[] {
  return items.map((i) => `  - ${i}`);
}

function escTitle(s: string): string {
  return s.replace(/[\r\n]+/g, ' ').slice(0, 120);
}

function clamp01(x: number): number {
  if (!Number.isFinite(x)) return 0;
  return Math.max(0, Math.min(1, x));
}

function personaNotes(personas: PersonaLabPersona[] | null): string[] {
  if (!personas || personas.length === 0) return ['No persona set attached.'];
  const notes: string[] = [];
  notes.push(`${personas.length} persona${personas.length === 1 ? '' : 's'} on file.`);
  return notes;
}

function researchNotes(graph: ResearchGraph | null): string[] {
  if (!graph) return ['No research graph attached.'];
  const notes: string[] = [];
  if ((graph.stats?.nodes ?? 0) < 10) notes.push('Graph is sparse (<10 nodes).');
  if ((graph.contradictions?.length ?? 0) > 0) notes.push('Contradictions detected — review before proceeding.');
  return notes;
}

function riskNotes(risks: EvaluationReportRiskItem[], contradictions: { left: string; right: string }[]): string[] {
  const notes: string[] = [];
  if (risks.length === 0) notes.push('No risks identified — check recommendation/committee coverage.');
  const highs = risks.filter((r) => r.severity === 'high').length;
  if (highs > 0) notes.push(`${highs} high-severity risk${highs === 1 ? '' : 's'}.`);
  if (contradictions.length > 0) notes.push(`${contradictions.length} contradiction${contradictions.length === 1 ? '' : 's'} unresolved.`);
  return notes;
}

function collectRisks(
  rec: VentureRecommendation | null,
  committee: BuyingCommitteeTranscript | null,
  graph: ResearchGraph | null,
): EvaluationReportRiskItem[] {
  const out: EvaluationReportRiskItem[] = [];
  if (rec) {
    for (const r of rec.risks) out.push({ label: r.risk, severity: mapSeverity(r), source: 'recommendation' });
  }
  if (committee) {
    const objections = (committee as unknown as { objections?: string[] }).objections ?? [];
    for (const o of objections.slice(0, 5)) out.push({ label: o, severity: 'med', source: 'committee' });
  }
  if (graph?.contradictions) {
    for (const c of graph.contradictions.slice(0, 3)) {
      out.push({ label: `Contradiction: ${c}`, severity: 'med', source: 'graph' });
    }
  }
  return out;
}

function mapSeverity(r: VentureRisk): EvaluationReportRiskItem['severity'] {
  const impact = r.impact === 'high' ? 2 : r.impact === 'medium' ? 1 : 0;
  const likelihood = r.likelihood === 'high' ? 2 : r.likelihood === 'medium' ? 1 : 0;
  const score = impact + likelihood;
  if (score >= 3) return 'high';
  if (score >= 2) return 'med';
  return 'low';
}

function deriveSuccessCriteria(pack: BuildSquadArtifactPack | null): string[] {
  if (!pack) return ['_No BuildSquad pack — define success metrics during planning._'];
  return pack.productVision.successMetrics.length > 0
    ? pack.productVision.successMetrics
    : ['_Pack present but no success metrics captured._'];
}

function deriveKillCriteria(rec: VentureRecommendation | null): string[] {
  if (!rec) return ['_No recommendation yet — define kill criteria during validation._'];
  if (rec.decision === 'KILL') return rec.decisionRationale.slice(0, 5);
  return rec.nextSteps
    .filter((s) => s.blocksDecision)
    .slice(0, 5)
    .map((s) => `Kill if blocked by: ${s.title}`);
}
