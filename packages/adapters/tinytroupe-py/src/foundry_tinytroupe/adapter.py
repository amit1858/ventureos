# ── Phased deliberation helpers (Sprint 1D.5) ───────────────────────────────

_POSITION_KEYWORDS: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("reject",                ("reject", "no thanks", "won't", "will not", "blocker", "deal-breaker")),
    ("pilot_first",           ("pilot", "trial", "try first", "evaluate first", "30-day", "60-day", "90-day")),
    ("support_with_concerns", ("but ", "however", "concern", "worry", "afraid", "risk", "provided that")),
    ("support",               ("support", "love it", "great", "excited", "buy", "purchase", "yes", "sign", "perfect")),
)

_POSITION_TO_STANCE = {
    "support": "champion",
    "support_with_concerns": "supporter",
    "pilot_first": "neutral",
    "reject": "blocker",
}


def _infer_position(text: str) -> str:
    """Map a free-form utterance to one of the four committee positions."""
    if not text:
        return "support_with_concerns"
    lower = text.lower()
    # Walk in priority order: reject > pilot > support_with_concerns > support.
    for label, hints in _POSITION_KEYWORDS:
        if any(h in lower for h in hints):
            return label
    return "support_with_concerns"


def _to_opinion(persona: dict[str, Any], utterances: list[str]) -> dict[str, Any]:
    joined = " ".join(utterances).strip()
    position = _infer_position(joined)
    concerns = _extract_objections(utterances)
    enthusiasm = {
        "support": 0.9,
        "support_with_concerns": 0.6,
        "pilot_first": 0.5,
        "reject": 0.2,
    }[position]
    return {
        "personaId": persona.get("id", ""),
        "position": position,
        "enthusiasm": enthusiasm,
        "concerns": concerns,
        "willingnessToAdopt": joined[:160] if joined else "",
        "rationale": joined[:400] if joined else "TinyTroupe agent produced no utterance in this phase.",
    }


def _to_challenges(
    personas: list[dict[str, Any]],
    agents: list[Any],
    phase_utterances: dict[str, list[str]],
    agent_key: Any,
) -> list[dict[str, Any]]:
    ids = [p.get("id", "") for p in personas]
    names_lower = {agent_key(a).lower(): p.get("id", "") for p, a in zip(personas, agents, strict=False)}
    out: list[dict[str, Any]] = []
    for persona, agent in zip(personas, agents, strict=False):
        key = agent_key(agent)
        utts = phase_utterances.get(key, [])
        if not utts:
            continue
        # Address-detection: look for another participant's name in the utterance.
        joined = " ".join(utts)
        target_id = ""
        joined_lower = joined.lower()
        for name_lower, pid in names_lower.items():
            if pid == persona.get("id", ""):
                continue
            if name_lower and name_lower in joined_lower:
                target_id = pid
                break
        if not target_id:
            # Fall back to the first other participant.
            others = [pid for pid in ids if pid != persona.get("id", "")]
            target_id = others[0] if others else ""
        if not target_id:
            continue
        out.append({
            "fromPersonaId": persona.get("id", ""),
            "toPersonaId": target_id,
            "topic": _infer_topic(joined),
            "argument": joined.strip()[:400],
        })
    return out


_TOPIC_KEYWORDS: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("pricing",    ("price", "cost", "expensive", "cheap", "budget", "fee")),
    ("onboarding", ("onboard", "setup", "install", "deploy", "training")),
    ("roi",        ("roi", "return", "value", "payback", "revenue", "growth")),
    ("workflow",   ("workflow", "click", "process", "step", "daily", "team")),
    ("trust",      ("trust", "security", "data", "privacy", "compliance")),
    ("assumption", ("assume", "assumption", "premise", "hypothesis")),
)


def _infer_topic(text: str) -> str:
    lower = text.lower()
    for label, hints in _TOPIC_KEYWORDS:
        if any(h in lower for h in hints):
            return label
    return "other"


def _to_responses(
    personas: list[dict[str, Any]],
    agents: list[Any],
    phase_utterances: dict[str, list[str]],
    agent_key: Any,
    challenges: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for persona, agent in zip(personas, agents, strict=False):
        key = agent_key(agent)
        utts = phase_utterances.get(key, [])
        if not utts:
            continue
        joined = " ".join(utts).strip()
        # Match this responder to the first challenge addressed AT them.
        idx = -1
        for i, c in enumerate(challenges):
            if c.get("toPersonaId") == persona.get("id", ""):
                idx = i
                break
        if idx < 0:
            continue
        lower = joined.lower()
        changed = any(p in lower for p in ("changed my mind", "you are right", "fair point", "i agree now", "i will pilot", "i'll pilot"))
        out.append({
            "fromPersonaId": persona.get("id", ""),
            "challengeIndex": idx,
            "argument": joined[:400],
            "changedOpinion": changed,
        })
    return out


def _compute_opinion_changes(
    initial: list[dict[str, Any]],
    consensus: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    initial_by_id = {o["personaId"]: o["position"] for o in initial}
    out: list[dict[str, Any]] = []
    for o in consensus:
        before = initial_by_id.get(o["personaId"])
        if before and before != o["position"]:
            out.append({
                "personaId": o["personaId"],
                "fromPosition": before,
                "toPosition": o["position"],
                "reason": "Position shifted during 4-phase deliberation.",
            })
    return out


def _derive_consensus_level(consensus: list[dict[str, Any]]) -> str:
    if not consensus:
        return "weak"
    positions = [o["position"] for o in consensus]
    unique = set(positions)
    if len(unique) == 1:
        return "strong"
    if len(unique) >= 3:
        return "split"
    # 2 unique positions
    top_count = max(positions.count(p) for p in unique)
    return "moderate" if top_count / len(consensus) >= 0.75 else "weak"


def _derive_decision_from_consensus(consensus: list[dict[str, Any]]) -> str:
    if not consensus:
        return "defer"
    counts = {"support": 0, "support_with_concerns": 0, "pilot_first": 0, "reject": 0}
    for o in consensus:
        pos = o.get("position", "support_with_concerns")
        if pos in counts:
            counts[pos] += 1
    if counts["reject"] > len(consensus) / 2:
        return "reject"
    if counts["support"] == len(consensus):
        return "buy"
    if counts["support"] + counts["support_with_concerns"] > len(consensus) / 2:
        return "pilot"
    return "defer"


def _collect_unresolved_objections(consensus: list[dict[str, Any]]) -> list[str]:
    out: list[str] = []
    for o in consensus:
        if o.get("position") in ("reject", "pilot_first"):
            for c in o.get("concerns", []):
                if c and c not in out:
                    out.append(c)
    return out[:8]


def _strongest(consensus: list[dict[str, Any]], *, supporting: bool) -> list[str]:
    out: list[str] = []
    for o in consensus:
        pos = o.get("position", "")
        if supporting and pos in ("support", "support_with_concerns"):
            r = o.get("rationale", "")
            if r:
                out.append(r[:200])
        elif not supporting and pos in ("reject", "pilot_first"):
            r = o.get("rationale", "")
            if r:
                out.append(r[:200])
    return out[:5]


def _derive_members(
    personas: list[dict[str, Any]],
    initial: list[dict[str, Any]],
    consensus: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    final_by_id = {o["personaId"]: o for o in consensus}
    initial_by_id = {o["personaId"]: o for o in initial}
    out: list[dict[str, Any]] = []
    for p in personas:
        pid = p.get("id", "")
        opinion = final_by_id.get(pid) or initial_by_id.get(pid)
        if not opinion:
            out.append({
                "personaId": pid,
                "committeeRole": p.get("role", "Participant"),
                "stance": "neutral",
                "rationale": "",
                "blockingObjections": [],
            })
            continue
        position = opinion.get("position", "support_with_concerns")
        stance = _POSITION_TO_STANCE.get(position, "neutral")
        # Refine by enthusiasm.
        enth = float(opinion.get("enthusiasm", 0.5))
        if stance == "champion" and enth < 0.7:
            stance = "supporter"
        if stance == "blocker" and enth > 0.3:
            stance = "skeptic"
        objections = list(opinion.get("concerns", [])) if position in ("reject", "pilot_first") else []
        out.append({
            "personaId": pid,
            "committeeRole": p.get("role", "Participant"),
            "stance": stance,
            "rationale": opinion.get("rationale", ""),
            "blockingObjections": objections,
        })
    return out
